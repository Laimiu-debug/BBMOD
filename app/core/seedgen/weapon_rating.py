"""Explainable named-weapon affix ratings, shared with the in-game filter.

This is an explicit damage/penetration-first preference model, not simulated
DPS. Roll quality measures only the two selected affixes, including their
benefit direction. Base stats, durability and builds are not scored.
"""
from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache
import json
import re

from ..item_inspector import catalog, rolls_for

MODEL = '伤穿优先 v1'
# In NamedAttr order; the generated Squirrel configuration uses these names.
WEIGHTS = {
    'RegularDamage': 100, 'ArmorDamageMult': 70, 'ChanceToHitHead': 30,
    'DirectDamageAdd': 90, 'StaminaModifier': 40, 'ShieldDamage': 20,
    'AmmoMax': 25, 'AdditionalAccuracy': 85, 'FatigueOnSkillUse': 55,
}
RATING_EXPLANATION = '''红武评分 · 伤穿优先 v1

实用词条评分：0–100 分，优先伤害、穿甲和命中。适合比较同类武器的词条组合，不代表实战伤害、胜率或跨武器强弱。
权重：伤害 100、穿甲 90、命中 85、破甲 70、技能减耗 55、疲劳减负 40、爆头 30、弹药 25、破盾 20。
每条贡献 = 权重 × (100 + 品质)；两条贡献之和 ÷ (该武器可抽中词条的最高两项权重之和 × 2)，四舍五入。保留半数基础贡献，以体现低 roll 词条仍有加成。

roll 品质：已抽中两条词条的品质平均值，0% 为各自最低收益，100% 为各自最高收益。它不评价词条组合；满 roll 的弹药、破盾组合也可能实用分偏低。
疲劳负担词条已反向处理，减负越多品质越高；技能疲劳减少越多品质也越高。耐久不占这两条词条，不计入评分。

筛选中的伤害、穿甲、实用分与 roll 门槛须由同一件武器同时满足；“不限”不要求该项，“0%”伤害或穿甲仍要求抽中该词条。
全部满足：各行是独立数量，同一件武器不重复计数；任一满足：找到任意一行要求即可。全地图红装总数始终还须满足。

按原版 1.5.2.3 的 50 种红武词条池计算。记录缺少两条完整词条、武器未收录或词条不在该武器原版词条池时暂不评分，也不通过评分门槛。历史日志有完整词条记录即可自动显示评分。'''


@lru_cache(maxsize=1)
def eligible_affixes() -> dict[str, tuple[str, ...]]:
    return {identifier: tuple(roll.keys[0] for roll in rolls_for(item) if roll.optional)
            for identifier, item in catalog().items() if item['kind'] == 'weapon'}


@dataclass(frozen=True)
class WeaponRating:
    score: int
    quality: int
    affixes: tuple[tuple[str, int], ...]


def rate_weapon(identifier: str, rolls: dict[str, int]) -> WeaponRating | None:
    eligible = eligible_affixes().get(identifier)
    if (not eligible or not isinstance(rolls, dict) or len(rolls) != 2
            or any(key not in eligible or key not in WEIGHTS or type(value) is not int
                   or not 0 <= value <= 100 for key, value in rolls.items())):
        return None
    # The logger records the random multiplier for StaminaModifier (50..80),
    # where a smaller multiplier means a smaller negative fatigue burden.
    affixes = tuple((key, 100 - value if key == 'StaminaModifier' else value)
                    for key, value in rolls.items())
    top = sum(sorted((WEIGHTS[key] for key in eligible), reverse=True)[:2])
    numerator = sum(WEIGHTS[key] * (100 + quality) for key, quality in affixes)
    denominator = 2 * top
    return WeaponRating((numerator + denominator // 2) // denominator,
                        (sum(quality for _, quality in affixes) + 1) // 2, affixes)


_WEAPON_LINE = re.compile(
    r'ItemInfo\((?:OneHanded|TwoHanded|RangedWeapon)\):\s*([^\s(]+)\(([^)]*)\)(?:\s|$)')


def rate_weapon_line(line: str) -> WeaponRating | None:
    match = _WEAPON_LINE.match(line.strip())
    if not match:
        return None
    entries = match[2].split('|')
    pairs = [re.fullmatch(r'(\w+):(\d{1,3})(?:\.0+)?%', entry) for entry in entries]
    if len(pairs) != 2 or not all(pairs) or pairs[0][1] == pairs[1][1]:
        return None
    return rate_weapon(match[1], {pair[1]: int(pair[2]) for pair in pairs})


def emit_weapon_rating() -> str:
    """Generate the game's constants from the exact model used for display."""
    lines = ['// Generated by BBMOD: ' + MODEL,
             'local gt = this.getroottable();',
             'gt.SeedGenerator.WeaponRatingWeights <- [' + ', '.join(map(str, WEIGHTS.values())) + '];',
             'gt.SeedGenerator.WeaponRatingEligible <- {']
    for identifier, keys in eligible_affixes().items():
        indices = ', '.join(str(list(WEIGHTS).index(key)) for key in keys)
        lines.append(f'    [{json.dumps(identifier)}] = [{indices}],')
    return '\n'.join([*lines, '};', ''])
